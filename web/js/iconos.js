// Reemplaza <i data-icono="nombre"></i> por el SVG correspondiente
export function pintarIconos(raiz = document) {
  for (const el of raiz.querySelectorAll("[data-icono]")) {
    el.outerHTML = icono(el.dataset.icono);
  }
}
